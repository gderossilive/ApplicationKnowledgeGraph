    Units INT NULL CONSTRAINT DF_TicketLines_Units DEFAULT 0,
    Code INT NULL CONSTRAINT DF_TicketLines_Code DEFAULT 0,
    TicketID INT NULL CONSTRAINT DF_TicketLines_TicketID DEFAULT 0,
