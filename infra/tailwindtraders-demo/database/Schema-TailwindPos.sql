IF OBJECT_ID(N'dbo.Tickets', N'U') IS NULL
CREATE TABLE dbo.Tickets (
    TicketID INT IDENTITY(1, 1) NOT NULL PRIMARY KEY,
    Ticket_DateTime DATETIME NULL,
    Total MONEY NULL CONSTRAINT DF_Tickets_Total DEFAULT 0,
    Taxes MONEY NULL CONSTRAINT DF_Tickets_Taxes DEFAULT 0,
    CustomerID INT NULL CONSTRAINT DF_Tickets_CustomerID DEFAULT 0,
    POSID INT NULL CONSTRAINT DF_Tickets_POSID DEFAULT 0,
    UserID INT NULL CONSTRAINT DF_Tickets_UserID DEFAULT 0,
    Status INT NULL CONSTRAINT DF_Tickets_Status DEFAULT 0
);

